export type AdminMessageKey = keyof (typeof adminMessages)["de"];

export function isAdminLocale(value: string): value is AppLocale {
  return (SUPPORTED_LOCALES as readonly string[]).includes(value);
}

export function adminT(locale: AppLocale, key: AdminMessageKey): string {
  return adminMessages[locale][key] ?? adminMessages[DEFAULT_LOCALE][key];
}
